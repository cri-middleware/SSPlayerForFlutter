// ffigen generator: the low-level dart:ffi bindings for the SpriteStudio-SDK
// converter (libssconverter), from the C-API header the SDK build.rs emits
// (native/include/ssconverter.h, copied in by build-runtime). No cbindgen here.
//
// Regenerate with:  scripts/generate-ffigen-code.sh  (runs packages/*/tool/ffigen.dart;
// standalone — run after a C-API change). The output is COMMITTED.
import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final packageRoot = Platform.script.resolve('../');

  await FfiGenerator(
    input: Input(
      entryPoints: [packageRoot.resolve('native/include/ssconverter.h')],
      include: (header) => header.pathSegments.last == 'ssconverter.h',
    ),
    output: Output(
      dart: DartOutput(
        path: packageRoot.resolve('lib/src/ssconverter_bindings.g.dart'),
      ),
      // Native assets: generate top-level `@Native(assetId: ...)` functions that
      // resolve the code asset bundled by hook/build.dart. Must match
      // CodeAsset(name: 'ssconverter').
      style: const NativeExternalBindings(
        assetId: 'package:ssconverter_dart/ssconverter',
      ),
      commentType: const CommentType(CommentStyle.any, CommentLength.full),
      preamble:
          '// GENERATED by ffigen (scripts/generate-ffigen-code.sh). Do not edit by hand.\n'
          '// ignore_for_file: type=lint, unused_field, unused_element, camel_case_types, non_constant_identifier_names\n',
    ),
    visitors: [
      Visitor(
        func: (node) =>
            node.isIncluded = node.originalName.startsWith('ss_converter_'),
        struct: (node) => node.isIncluded = node.originalName == 'Context',
        enumClass: (node) =>
            node.isIncluded = node.originalName == 'CConverterError',
        typealias: (node) =>
            node.isIncluded = node.originalName == 'LogCallback'
            ? TypealiasInclude.ifUsed
            : TypealiasInclude.never,
        macroConstant: (node) => node.isIncluded = true,
      ),
    ],
  ).generate();
}
