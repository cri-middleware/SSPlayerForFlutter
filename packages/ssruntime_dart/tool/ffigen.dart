// ffigen generator: the Layer 1 dart:ffi bindings, from the C-API header the
// SDK build.rs emits (native/include/ssruntime.h, copied in by build-runtime).
//
// Regenerate with:  scripts/generate-ffigen-code.sh  (runs packages/*/tool/ffigen.dart;
// standalone — run after a C-API change). The output is COMMITTED.
import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final packageRoot = Platform.script.resolve('../');
  bool exported(String name) => name.startsWith('ss_') || name.startsWith('Ss');

  await FfiGenerator(
    input: Input(
      entryPoints: [packageRoot.resolve('native/include/ssruntime.h')],
      include: (header) => header.pathSegments.last == 'ssruntime.h',
    ),
    output: Output(
      dart: DartOutput(
        path: packageRoot.resolve('lib/src/ssruntime_bindings.g.dart'),
      ),
      // Native assets: generate top-level `@Native(assetId: ...)` functions that
      // resolve the code asset bundled by hook/build.dart.
      // The asset id MUST match the hook's CodeAsset(package: 'ssruntime_dart',
      // name: 'ssruntime').
      style: const NativeExternalBindings(
        assetId: 'package:ssruntime_dart/ssruntime',
      ),
      commentType: const CommentType(CommentStyle.any, CommentLength.full),
      preamble:
          '// GENERATED by ffigen (scripts/generate-ffigen-code.sh). Do not edit by hand.\n'
          '// ignore_for_file: type=lint, unused_field, unused_element, camel_case_types, non_constant_identifier_names\n',
    ),
    visitors: [
      Visitor(
        func: (node) {
          node.isIncluded = node.originalName.startsWith('ss_');
          // A leaf call, so the Body can pass a `Uint8List.address` (a pointer
          // straight into the Dart-heap backing store) instead of malloc'ing a
          // native scratch copy: `ss_resource_create_copy` copies the bytes onto
          // the Brain's own heap synchronously and never retains the pointer,
          // and a leaf call has no safepoint so the GC cannot move the list
          // mid-call. See NativeRuntime.createResourceCopy.
          if (node.originalName == 'ss_resource_create_copy') {
            node.isLeaf = true;
          }
        },
        struct: (node) => node.isIncluded = exported(node.originalName),
        enumClass: (node) => node.isIncluded = exported(node.originalName),
        typealias: (node) =>
            node.isIncluded = node.originalName.startsWith('Ss')
            ? TypealiasInclude.ifUsed
            : TypealiasInclude.never,
        macroConstant: (node) => node.isIncluded = true,
      ),
    ],
  ).generate();
}
